function Icon({ paths, color = '#999', size = 24, strokeWidth = 1.8 }: IconInnerProps) {
  return (
    <Svg width={size} height={size} viewBox="0 0 24 24" fill="none">
      {paths.map((d, i) => (
        <Path
          key={i}
          d={d}
          fill="none"
          stroke={color}
          strokeWidth={strokeWidth}
          strokeLinecap="round"
          strokeLinejoin="round"
        />
      ))}
    </Svg>
  );
}

function makeIcon(paths: string[]) {
  return function IconComponent(props: IconProps) {
    return <Icon {...props} paths={paths} />;
  };
}

